/**
 * The six animals (docs/ART-AND-SHOP.md §2), as pixel maps.
 *
 * Each animal sits in its ring seen from behind and a little above: the back
 * of the head, the ears, and the arms out to the sides holding on. Its bottom
 * rows are drawn too, but in the game they sit behind the ring's front half.
 *
 * Three poses are drawn by hand for every animal, so each keeps its own
 * personality: idle, jump (arms up, ears and feathers flying) and crash
 * (popped up, arms flung out, stars over its head). The other moves are
 * worked out from those three rather than drawn again: the bob is the idle
 * frame moved a pixel, the duck and the landing are the idle frame sunk into
 * the ring, and the lean is the idle frame sheared sideways (see `leanRows`).
 *
 * Every character is looked up in SPRITE_LEGEND. Plain data and no Three.js,
 * so the maps are tested on their own in node.
 */

