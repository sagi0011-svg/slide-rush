/**
 * The lean, worked out from the idle frame: every row slides sideways by an
 * amount that grows towards the top, so the head leans into the turn while
 * the bottom stays sat in the ring. Drawn leaning right; the left lean is the
 * same frame mirrored when it is drawn.
 */
export function leanRows(rows: readonly string[], shear: number = RIDER.leanShearPixels): string[] {
  const height = rows.length;
  return rows.map((row, y) => {
    const shift = Math.round(((height - 1 - y) / (height - 1)) * shear);
    if (shift === 0) return row;
    return CLEAR.repeat(shift) + row.slice(0, row.length - shift);
  });
}

/** The pixel map for one frame of one animal. */
export function animalRows(id: AnimalId, frame: AnimalFrame): readonly string[] {
  const sprite = ANIMAL_SPRITES[id];
  return frame === 'lean' ? leanRows(sprite.idle) : sprite[frame];
}
